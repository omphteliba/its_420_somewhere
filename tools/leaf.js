"use strict";
// Generates the app icon (icon.svg): a clock showing 4:20 over a cannabis leaf.
// Usage: node tools/leaf.js

const fs = require("fs");
const path = require("path");

// Seven-fingered, serrated leaf in a 100x100 box (stem base at bottom centre).
function leafPath() {
  const cx = 50;
  const cy = 64;
  const fingers = [[0, 1], [-30, 0.86], [30, 0.86], [-60, 0.66], [60, 0.66], [-92, 0.4], [92, 0.4]];
  const STEPS = 14;
  const r = (n) => Math.round(n * 10) / 10;

  const finger = ([deg, rel]) => {
    const len = 52 * rel;
    const wid = len * 0.16;
    const a = (deg * Math.PI) / 180;
    const pt = (along, side) => [
      r(cx + Math.sin(a) * along + Math.cos(a) * side),
      r(cy - Math.cos(a) * along + Math.sin(a) * side),
    ];
    const right = [];
    const left = [];
    for (let i = 1; i < STEPS; i++) {
      const t = i / STEPS;
      const w = wid * Math.pow(Math.sin(Math.PI * Math.pow(t, 0.85)), 0.9) * (i % 2 ? 1 : 0.7);
      right.push(pt(len * t, w));
      left.unshift(pt(len * t, -w));
    }
    return "M" + [[cx, cy], ...right, pt(len, 0), ...left].map((p) => p.join(",")).join("L") + "Z";
  };

  const stem = `M${cx - 1.6},${cy}L${cx + 1.6},${cy}L${cx + 1},96L${cx - 1},96Z`;
  return fingers.map(finger).join("") + stem;
}

// Clock hands for 4:20 → hour hand at 130°, minute hand at 120°.
function hand(deg, len) {
  const a = (deg * Math.PI) / 180;
  return [50 + Math.sin(a) * len, 50 - Math.cos(a) * len].map((n) => n.toFixed(1));
}
const [hx, hy] = hand(130, 20);
const [mx, my] = hand(120, 30);
const ticks = Array.from({ length: 12 }, (_, i) => {
  const a = (i * 30 * Math.PI) / 180;
  const p = (r) => [50 + Math.sin(a) * r, 50 - Math.cos(a) * r].map((n) => n.toFixed(1));
  const [x1, y1] = p(38);
  const [x2, y2] = p(i % 3 ? 40.5 : 42);
  return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`;
}).join("");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
<circle cx="50" cy="50" r="47" fill="#fbf9ef" stroke="#3f8f48" stroke-width="5"/>
<g transform="translate(50 52) scale(0.62) translate(-50 -58)"><path fill="#8fcf72" d="${leafPath()}"/></g>
<g stroke="#2f5d34" stroke-width="2.4" stroke-linecap="round">${ticks}</g>
<g stroke="#26352a" stroke-linecap="round">
<line x1="50" y1="50" x2="${hx}" y2="${hy}" stroke-width="5"/>
<line x1="50" y1="50" x2="${mx}" y2="${my}" stroke-width="3.4"/>
</g>
<circle cx="50" cy="50" r="3.6" fill="#26352a"/>
</svg>
`;

fs.writeFileSync(path.join(__dirname, "..", "icon.svg"), svg);

// Plain white leaf for the strain cards.
const leaf = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><path fill="#ffffff" d="${leafPath()}"/></svg>\n`;
fs.writeFileSync(path.join(__dirname, "..", "leaf.svg"), leaf);

// Raw path for the leaf sea in the hero card.
fs.writeFileSync(
  path.join(__dirname, "..", "leaf-path.js"),
  `// Generated by tools/leaf.js – do not edit.\nconst LEAF_PATH = "${leafPath()}";\n`
);
console.log("wrote icon.svg, leaf.svg, leaf-path.js");
